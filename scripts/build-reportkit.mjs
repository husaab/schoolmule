#!/usr/bin/env node
/**
 * Bundle src/reportkit into the backend's PDF printer.
 *
 *   npm run sync:reportkit            build + copy into ../schoolmule-backend
 *   npm run sync:reportkit -- --check exit 1 when the backend copy is stale
 *
 * Writes <backend>/vendor/reportkit/{reportkit.iife.js, manifest.json, fonts/, assets/}.
 * assets/ holds the built-in images (public/report-assets, the engine's
 * `{ kind: 'builtin' }` image sources), which the printer inlines.
 * The backend repo is a sibling checkout; override with REPORTKIT_BACKEND_DIR.
 * The manifest's sourceHash covers every engine source file, font and
 * built-in image, so either repo's tests can tell when the committed bundle
 * is out of date.
 */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { ASSET_FILE, reportkitEngineVersion, reportkitSourceHash } from './reportkit-source.mjs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(webRoot, 'src/reportkit');
const fontDir = join(webRoot, 'public/report-fonts');
const assetDir = join(webRoot, 'public/report-assets');
const backendDir = resolve(webRoot, process.env.REPORTKIT_BACKEND_DIR ?? '../schoolmule-backend');
const outDir = join(backendDir, 'vendor/reportkit');
const check = process.argv.includes('--check');

const hash = reportkitSourceHash(webRoot);
const ENGINE_VERSION = reportkitEngineVersion(webRoot);

if (check) {
  const manifestPath = join(outDir, 'manifest.json');
  if (!existsSync(manifestPath)) {
    console.error(`No bundle at ${outDir}. Run npm run sync:reportkit.`);
    process.exit(1);
  }
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  if (manifest.sourceHash !== hash) {
    console.error('The backend reportkit bundle is out of date. Run npm run sync:reportkit and commit both repos.');
    process.exit(1);
  }
  console.log('reportkit bundle is up to date.');
  process.exit(0);
}

if (!existsSync(backendDir)) {
  console.error(`Backend checkout not found at ${backendDir} (set REPORTKIT_BACKEND_DIR).`);
  process.exit(1);
}

const result = await build({
  entryPoints: [join(srcDir, 'index.ts')],
  bundle: true,
  format: 'iife',
  globalName: 'ReportKit',
  platform: 'browser',
  target: ['chrome110'],
  minify: true,
  legalComments: 'none',
  write: false,
});
const code = result.outputFiles[0].text;


rmSync(outDir, { recursive: true, force: true });
mkdirSync(join(outDir, 'fonts'), { recursive: true });
mkdirSync(join(outDir, 'assets'), { recursive: true });
writeFileSync(join(outDir, 'reportkit.iife.js'), code);
for (const f of readdirSync(fontDir)) {
  if (f.endsWith('.woff2') || f === 'LICENSES.md') cpSync(join(fontDir, f), join(outDir, 'fonts', f));
}
for (const f of readdirSync(assetDir)) {
  if (ASSET_FILE.test(f)) cpSync(join(assetDir, f), join(outDir, 'assets', f));
}
const manifest = {
  engineVersion: ENGINE_VERSION,
  sourceHash: hash,
  bundleSha256: createHash('sha256').update(code).digest('hex'),
  note: 'Generated by schoolmule/scripts/build-reportkit.mjs — do not edit. Source: schoolmule/src/reportkit.',
};
writeFileSync(join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
writeFileSync(
  join(outDir, 'README.md'),
  `# vendor/reportkit — generated, do not edit

The report engine that prints every report card and progress report
(services/reportEngine/render.js). It is the same code the web designer runs,
so a PDF lays out exactly like the admin's preview.

- Source: schoolmule/src/reportkit (TypeScript, web repo).
- Rebuild with \`npm run sync:reportkit\` in the web repo (from a worktree:
  \`REPORTKIT_BACKEND_DIR=<this repo> npm run sync:reportkit\`), then commit BOTH repos.
- \`npm run check:reportkit\` (web) and __tests__/unit/services/reportEngine/vendorBundle.test.js
  (here) fail when this copy is stale or hand-edited.
- manifest.json: engineVersion (stamped on generated reports), sourceHash, bundleSha256.
`,
);
console.log(`reportkit v${ENGINE_VERSION} → ${relative(process.cwd(), outDir)} (${(code.length / 1024).toFixed(1)} KB)`);
