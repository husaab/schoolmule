#!/usr/bin/env node
/**
 * Bundle src/reportkit into the backend's PDF printer.
 *
 *   npm run sync:reportkit            build + copy into ../schoolmule-backend
 *   npm run sync:reportkit -- --check exit 1 when the backend copy is stale
 *
 * Writes <backend>/vendor/reportkit/{reportkit.iife.js, manifest.json, fonts/}.
 * The backend repo is a sibling checkout; override with REPORTKIT_BACKEND_DIR.
 * The manifest's sourceHash covers every engine source file and font, so
 * either repo's tests can tell when the committed bundle is out of date.
 */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(webRoot, 'src/reportkit');
const fontDir = join(webRoot, 'public/report-fonts');
const backendDir = resolve(webRoot, process.env.REPORTKIT_BACKEND_DIR ?? '../schoolmule-backend');
const outDir = join(backendDir, 'vendor/reportkit');
const check = process.argv.includes('--check');

function walk(dir) {
  return readdirSync(dir)
    .flatMap((name) => {
      const p = join(dir, name);
      return statSync(p).isDirectory() ? walk(p) : [p];
    })
    .sort();
}

/** Hash of every engine source (tests excluded) and font file. */
export function sourceHash() {
  const h = createHash('sha256');
  const files = [
    ...walk(srcDir).filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts')),
    ...walk(fontDir).filter((f) => f.endsWith('.woff2')),
  ];
  for (const f of files) {
    h.update(relative(webRoot, f));
    h.update(readFileSync(f));
  }
  return h.digest('hex');
}

const hash = sourceHash();

if (check) {
  const manifestPath = join(outDir, 'manifest.json');
  if (!existsSync(manifestPath)) {
    console.error(`No bundle at ${outDir}. Run npm run sync:reportkit.`);
    process.exit(1);
  }
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  if (manifest.sourceHash !== hash) {
    console.error('The backend reportkit bundle is out of date. Run npm run sync:reportkit and commit both repos.');
    process.exit(1);
  }
  console.log('reportkit bundle is up to date.');
  process.exit(0);
}

if (!existsSync(backendDir)) {
  console.error(`Backend checkout not found at ${backendDir} (set REPORTKIT_BACKEND_DIR).`);
  process.exit(1);
}

const result = await build({
  entryPoints: [join(srcDir, 'index.ts')],
  bundle: true,
  format: 'iife',
  globalName: 'ReportKit',
  platform: 'browser',
  target: ['chrome110'],
  minify: true,
  legalComments: 'none',
  write: false,
});
const code = result.outputFiles[0].text;

const { ENGINE_VERSION } = await import(`data:text/javascript,${encodeURIComponent(`${code};export const ENGINE_VERSION = ReportKit.ENGINE_VERSION;`)}`).catch(
  () => ({ ENGINE_VERSION: null }),
);

rmSync(outDir, { recursive: true, force: true });
mkdirSync(join(outDir, 'fonts'), { recursive: true });
writeFileSync(join(outDir, 'reportkit.iife.js'), code);
for (const f of readdirSync(fontDir)) {
  if (f.endsWith('.woff2') || f === 'LICENSES.md') cpSync(join(fontDir, f), join(outDir, 'fonts', f));
}
const manifest = {
  engineVersion: ENGINE_VERSION,
  sourceHash: hash,
  bundleSha256: createHash('sha256').update(code).digest('hex'),
  note: 'Generated by schoolmule/scripts/build-reportkit.mjs — do not edit. Source: schoolmule/src/reportkit.',
};
writeFileSync(join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`reportkit v${ENGINE_VERSION} → ${relative(process.cwd(), outDir)} (${(code.length / 1024).toFixed(1)} KB)`);
